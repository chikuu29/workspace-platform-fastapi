"""
Receipt Service — read-only receipt management.

Receipts are auto-generated when an invoice is fully paid.
This service provides read access and the internal _generate_receipt()
method called by PaymentService — NOT by domain apps directly.

Inherits from BaseBillingService for shared infrastructure.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from motor.motor_asyncio import AsyncIOMotorDatabase

from app.common.responses import not_found
from app.core.context import OrgContext
from app.modules.billing.constants import (
    DEFAULT_CURRENCY,
    ENTITY_RECEIPT,
    ReceiptStatus,
)
from app.modules.billing.documents.invoice_doc import InvoiceDoc
from app.modules.billing.documents.order_doc import OrderDoc
from app.modules.billing.documents.payment_doc import PaymentDoc
from app.modules.billing.documents.receipt_doc import ReceiptDoc
from app.modules.billing.services.base import BaseBillingService


class ReceiptService(BaseBillingService):
    """
    Receipt management — read-only service with internal generation.

    Receipts are auto-generated by PaymentService when an invoice
    is fully paid. This service provides read access and the internal
    generation method.

    Public methods (read-only):
        get(receipt_number)            — get a single receipt
        get_for_invoice(invoice_ref)   — get receipt for a specific invoice
        list(...)                      — list receipts

    Internal method (called by PaymentService):
        _generate_receipt(invoice, payments) — auto-generate on full payment
    """

    # ── BaseBillingService Abstract Properties ───────────────────

    @property
    def service_name(self) -> str:
        return "receipts"

    @property
    def entity_type(self) -> str:
        return ENTITY_RECEIPT

    @property
    def number_prefix(self) -> str:
        return "RCT"

    # ── Internal Generation (called by PaymentService) ───────────

    async def _generate_receipt(
        self,
        invoice: InvoiceDoc,
        payments: List[PaymentDoc],
    ) -> ReceiptDoc:
        """
        Auto-generate a receipt when an invoice is fully paid.

        Called by PaymentService._handle_full_payment() — NOT by domain apps.
        Creates a snapshot of invoice + payment data at the time of generation.

        Args:
            invoice: The fully paid InvoiceDoc.
            payments: All PaymentDocs that contributed to the full payment.

        Returns:
            The newly created ReceiptDoc.
        """
        # Check if receipt already exists for this invoice
        existing = await ReceiptDoc.find_by_invoice(
            self._ctx, invoice.invoice_number,
        )
        if existing:
            self._logger.warning(
                "Receipt already exists for invoice %s → %s",
                invoice.invoice_number, existing.receipt_number,
            )
            return existing

        receipt_number = await self._generate_number()
        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")

        # Determine primary payment method (from the last payment)
        primary_method = payments[-1].method if payments else ""
        payment_refs = [p.payment_number for p in payments]

        # Check for linked order
        order_ref = ""
        order = await OrderDoc.find_by_invoice(
            self._ctx, invoice.invoice_number,
        )
        if order:
            order_ref = order.order_number

        # Create receipt document
        doc = ReceiptDoc.create_for_org(
            self._ctx,
            entity_type=ENTITY_RECEIPT,
            record_id=receipt_number,
            receipt_number=receipt_number,
            invoice_ref=invoice.invoice_number,
            order_ref=order_ref,
            payment_refs=payment_refs,
            customer_ref=invoice.customer_ref,
            subtotal=invoice.subtotal,
            tax_amount=invoice.tax_breakdown.total_tax if invoice.tax_breakdown else 0.0,
            total=invoice.total,
            amount_paid=invoice.amount_paid,
            currency=invoice.currency or DEFAULT_CURRENCY,
            payment_method=primary_method,
            payment_date=now_str,
            status=ReceiptStatus.ISSUED,
            source_app=self._ctx.app_code,
        )

        await doc.insert()

        self._logger.info(
            "Generated receipt %s for invoice %s org=%s",
            receipt_number, invoice.invoice_number, self._ctx.org_id,
        )
        return doc

    # ── Public Methods (read-only) ───────────────────────────────

    async def get(self, receipt_number: str) -> ReceiptDoc:
        """Get a single receipt by its number."""
        doc = await ReceiptDoc.find_by_number(self._ctx, receipt_number)
        if not doc:
            not_found(message=f"Receipt '{receipt_number}' not found.")
        return doc

    async def get_for_invoice(
        self, invoice_ref: str,
    ) -> Optional[ReceiptDoc]:
        """Get the receipt for a specific invoice (if fully paid)."""
        return await ReceiptDoc.find_by_invoice(self._ctx, invoice_ref)

    async def list(
        self,
        *,
        skip: int = 0,
        limit: int = 50,
    ) -> tuple[List[ReceiptDoc], int]:
        """List receipts for the current org."""
        documents = await ReceiptDoc.org_find(
            self._ctx,
            {},
            sort=[("_meta.created.at", -1)],
            skip=skip,
            limit=limit,
        )
        total = await ReceiptDoc.org_count(self._ctx)
        return documents, total
